import { NextRequest, NextResponse } from 'next/server';
import { getAuth } from '@/lib/server/auth';
import pptxgen from 'pptxgenjs';
import { APPLIED_PHYSICS_SYLLABUS } from '@/lib/curricula-registry';

export async function POST(req: NextRequest) {
  try {
    const authResult = await getAuth();
    if (!authResult.ok) {
      return authResult.response;
    }

    const body = await req.json();
    const {
      title = 'SyllabusOS Study Presentation',
      topic = '',
      unitId = 'unit-1-laser-fiber',
      subjectName = 'Engineering Physics',
      sections = []
    } = body;
    const unit = APPLIED_PHYSICS_SYLLABUS.units.find((item) => item.id === unitId) || APPLIED_PHYSICS_SYLLABUS.units[0];
    const unitTopics = unit.subtopics;
    const selectedTopic = unitTopics.includes(topic) ? topic : unitTopics[0] || unit.title;

    // Initialize pptxgen instance
    const pres = new pptxgen();
    pres.layout = 'LAYOUT_16x9';
    pres.author = 'SyllabusOS AI Platform';
    pres.company = 'University Engineering Studies';
    pres.title = title;

    // Define color theme
    const BRAND_DARK = '1E1B4B'; // Indigo 950
    const BRAND_PRIMARY = '4F46E5'; // Indigo 600
    const BRAND_ACCENT = '059669'; // Emerald 600
    const BG_LIGHT = 'FBF9F4';

    // Slide 1: Title Slide
    const slide1 = pres.addSlide();
    slide1.background = { color: BRAND_DARK };
    slide1.addText(title, {
      x: 1.0,
      y: 2.0,
      w: 11.3,
      h: 1.5,
      fontSize: 36,
      bold: true,
      color: 'FFFFFF',
      fontFace: 'Arial'
    });
    slide1.addText(`${subjectName} • Unit ${unit.number}: ${unit.title.replace(/^UNIT-[IVX]+:\s*/, '')}`, {
      x: 1.0,
      y: 3.5,
      w: 11.3,
      h: 0.5,
      fontSize: 16,
      color: 'A5B4FC',
      fontFace: 'Arial'
    });
    slide1.addText('Generated by SyllabusOS — Syllabus-Aware AI Learning Platform', {
      x: 1.0,
      y: 5.8,
      w: 11.3,
      h: 0.4,
      fontSize: 11,
      color: '94A3B8',
      fontFace: 'Arial'
    });

    // Slide 2: Learning Objectives
    const slide2 = pres.addSlide();
    slide2.background = { color: BG_LIGHT };
    slide2.addText('Learning Objectives & Outcomes', {
      x: 0.8,
      y: 0.6,
      w: 11.5,
      h: 0.8,
      fontSize: 24,
      bold: true,
      color: BRAND_DARK,
      fontFace: 'Arial'
    });
    slide2.addText(
      [
        ...unitTopics.slice(0, 4).map((item: string) => ({ text: `• Understand ${item}\n` })),
        { text: `• Relate each topic to the selected focus: ${selectedTopic}` }
      ],
      {
        x: 0.8,
        y: 1.6,
        w: 11.5,
        h: 4.5,
        fontSize: 15,
        color: '334155',
        lineSpacing: 26,
        fontFace: 'Arial'
      }
    );

    // Slide 3: Core Theoretical Foundations
    const slide3 = pres.addSlide();
    slide3.background = { color: 'FFFFFF' };
    slide3.addText(`Unit ${unit.number}: Core Foundations`, {
      x: 0.8,
      y: 0.6,
      w: 11.5,
      h: 0.8,
      fontSize: 24,
      bold: true,
      color: BRAND_PRIMARY,
      fontFace: 'Arial'
    });

    const excerpt1 = sections[0]?.content
      ? sections[0].content.slice(0, 500)
      : `${unit.description}\n\nKey syllabus points:\n${unitTopics.slice(0, 5).map((item: string, index: number) => `${index + 1}. ${item}`).join('\n')}`;

    slide3.addText(excerpt1, {
      x: 0.8,
      y: 1.6,
      w: 11.5,
      h: 4.5,
      fontSize: 14,
      color: '1E293B',
      lineSpacing: 22,
      fontFace: 'Arial'
    });

    // Slide 4: Mathematical Equations & Derivations
    const slide4 = pres.addSlide();
    slide4.background = { color: BG_LIGHT };
    slide4.addText(`Unit ${unit.number}: Equations & Key Relations`, {
      x: 0.8,
      y: 0.6,
      w: 11.5,
      h: 0.8,
      fontSize: 24,
      bold: true,
      color: BRAND_DARK,
      fontFace: 'Arial'
    });

    slide4.addText(
      unitTopics.filter((item: string) => /[=<>√Δλπℏ]|equation|principle|law|condition/i.test(item)).slice(0, 7).map((item: string, index: number) => `${index + 1}. ${item}`).join('\n\n') || `Selected syllabus focus: ${selectedTopic}\n\nRefer to the course text for the governing equations and verify every symbol and SI unit against your lecture notes.`,
      {
        x: 0.8,
        y: 1.5,
        w: 11.5,
        h: 4.8,
        fontSize: 13,
        color: '1E293B',
        fontFace: 'Courier New'
      }
    );

    // Slide 5: Engineering Applications
    const slide5 = pres.addSlide();
    slide5.background = { color: 'FFFFFF' };
    slide5.addText(`Unit ${unit.number}: Applications & Connections`, {
      x: 0.8,
      y: 0.6,
      w: 11.5,
      h: 0.8,
      fontSize: 24,
      bold: true,
      color: BRAND_ACCENT,
      fontFace: 'Arial'
    });

    slide5.addText(
      unitTopics.slice(5).map((item: string) => `• ${item}`).join('\n\n') || unit.description,
      {
        x: 0.8,
        y: 1.6,
        w: 11.5,
        h: 4.5,
        fontSize: 14,
        color: '334155',
        lineSpacing: 22,
        fontFace: 'Arial'
      }
    );

    // Slide 6: Summary Slide
    const slide6 = pres.addSlide();
    slide6.background = { color: BRAND_DARK };
    slide6.addText('Summary & Exam Takeaways', {
      x: 0.8,
      y: 1.0,
      w: 11.5,
      h: 0.8,
      fontSize: 26,
      bold: true,
      color: 'FFFFFF',
      fontFace: 'Arial'
    });

    slide6.addText(
      [
        ...unitTopics.slice(0, 5).map((item: string) => ({ text: `✓ ${item}\n` }))
      ],
      {
        x: 0.8,
        y: 2.2,
        w: 11.5,
        h: 3.5,
        fontSize: 15,
        color: 'E2E8F0',
        lineSpacing: 28,
        fontFace: 'Arial'
      }
    );

    // Generate PPTX binary buffer
    const arrayBuffer = (await pres.write({ outputType: 'arraybuffer' })) as ArrayBuffer;
    const buffer = Buffer.from(arrayBuffer);

    const safeFilename = title.replace(/[^a-zA-Z0-9_-]/g, '_').slice(0, 40) + '.pptx';

    return new NextResponse(buffer, {
      status: 200,
      headers: {
        'Content-Type': 'application/vnd.openxmlformats-officedocument.presentationml.presentation',
        'Content-Disposition': `attachment; filename="${safeFilename}"`
      }
    });
  } catch (error: unknown) {
    console.error('Error generating PPTX in /api/materials/presentation:', error);
    const message = error instanceof Error ? error.message : 'Failed to generate presentation deck.';
    return NextResponse.json(
      { error: 'pptx_generation_failed', message },
      { status: 500 }
    );
  }
}
